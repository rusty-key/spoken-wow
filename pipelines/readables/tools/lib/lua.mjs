// The corpus, as the table the addon looks a page up in.
//
// Captions need the words for queued pages, including pages not yet opened in the client.
//
// A page is found by title, page number and a checksum of its text. Title and number alone
// are not enough: seven different books are called "Decoded Twilight Text" and each holds
// different words. The checksum alone is enough only when it is unique corpus-wide, which is
// what `loose` records -- a fallback for a client whose object name does not match ours.

import { pageChecksum } from "./naming.mjs";
import { cannotBeHad } from "./places.mjs";
import { shownText } from "./text.mjs";

/** Escape control bytes too: page text can contain newlines and tabs. */
export function quote(text) {
  return `"${String(text).replace(/\\/g, "\\\\").replace(/"/g, '\\"')
    .replace(/[\x00-\x1f\x7f]/g, (char) => `\\${char.charCodeAt(0).toString().padStart(3, "0")}`)}"`;
}

const HEADER = `-- AUTO-GENERATED by pipelines/readables/tools/export.mjs. Do not edit by hand.
--
-- The corpus is the "book_line" table on the site; this file is an export of it, committed
-- so the addon builds on a clone with no database. Regenerate with:  make readables-export
--
-- Page text supplies captions for the whole book, including unopened queued pages.
-- Checksums still use the original page text so the reader can identify the page.
--
-- A global rather than a private namespace, as the places data files are: a data file
-- cannot reach into the addon's environment.
`;

/** A page or book id as Lua writes it: a number bare, a minted id quoted. */
export function luaId(id) {
  return typeof id === "number" ? String(id) : quote(id);
}

export function compareIds(a, b) {
  return typeof a === "number" && typeof b === "number" ? a - b : String(a).localeCompare(String(b));
}

/**
 * The two tables a page is found by, in the shape the addon's Reader reads.
 *
 * @param entries rows of pageId (a number, or a quoted string for a minted page), bookId,
 *   pageNumber, either text or texts (a page is found under each) and either title or titles: a
 *   translated page is listed under each name its owners have in that language, and one
 *   whose owners have none is reachable only through `loose`
 * @returns index (title -> page number -> checksum -> pageId) and loose ([checksum, pageId]
 *   for checksums no other page shares)
 */
export function pageIndex(entries) {
  const sorted = [...entries].sort((a, b) => compareIds(a.bookId, b.bookId) || a.pageNumber - b.pageNumber);
  const checksums = new Map(sorted.map((entry) => [entry.pageId, [...new Set((entry.texts ?? [entry.text]).map(pageChecksum))]]));

  const index = new Map();
  for (const entry of sorted) {
    for (const title of entry.titles ?? [entry.title]) {
      if (!index.has(title)) index.set(title, new Map());
      const byNumber = index.get(title);
      if (!byNumber.has(entry.pageNumber)) byNumber.set(entry.pageNumber, new Map());
      const byChecksum = byNumber.get(entry.pageNumber);
      // First writer wins, and the rows arrive sorted, so the lowest book keeps the slot.
      // Four books are called "Inscribed Kodo Leather" and hold identical text: nothing on
      // screen distinguishes them, so the addon cannot either and the narration is the same
      // either way. Overwriting instead would make the answer depend on row order, which is
      // the kind of thing that changes under a re-extract and moves audio for no reason.
      for (const sum of checksums.get(entry.pageId)) {
        if (!byChecksum.has(sum)) byChecksum.set(sum, entry.pageId);
      }
    }
  }

  // An ambiguous checksum is dropped rather than resolved by order: guessing here narrates
  // the wrong page's words.
  const seen = new Map();
  for (const entry of sorted) {
    for (const sum of checksums.get(entry.pageId)) {
      seen.set(sum, seen.has(sum) ? null : entry.pageId);
    }
  }
  const loose = [...seen.entries()].filter(([, pageId]) => pageId !== null);

  return { index, loose };
}

/**
 * `index = {...}` and `loose = {...}`, one tab in, as fields of a table literal. A prefix
 * renames them `extraIndex` and `extraLoose`.
 */
export function indexLua({ index, loose }, prefix = "") {
  const lines = [`\t${prefix ? `${prefix}Index` : "index"} = {`];
  for (const title of [...index.keys()].sort()) {
    lines.push(`\t\t[${quote(title)}] = {`);
    for (const number of [...index.get(title).keys()].sort((a, b) => a - b)) {
      const byChecksum = index.get(title).get(number);
      const pairs = [...byChecksum.entries()]
        .sort(([a], [b]) => a - b)
        .map(([sum, pageId]) => `[${sum}] = ${luaId(pageId)}`);
      lines.push(`\t\t\t[${number}] = { ${pairs.join(", ")} },`);
    }
    lines.push("\t\t},");
  }

  lines.push("\t},", "", `\t${prefix ? `${prefix}Loose` : "loose"} = {`);
  for (const [sum, pageId] of [...loose].sort(([a], [b]) => a - b)) {
    lines.push(`\t\t[${sum}] = ${luaId(pageId)},`);
  }
  lines.push("\t},");
  return lines;
}

/**
 * The corpus rows of the books someone can have (places.mjs cannotBeHad): a retired, test or
 * never-given book is no page the reader can be shown.
 */
export function canBeHad(entries) {
  const texts = new Map();
  for (const entry of entries) {
    if (!texts.has(entry.bookId)) texts.set(entry.bookId, []);
    texts.get(entry.bookId).push(entry.text);
  }
  return entries.filter((entry) => !cannotBeHad(entry.title, texts.get(entry.bookId), entry.bookId));
}

/**
 * `owners = {...}`: item and object id -> the book it opens. An id that opens more than one
 * book is left out, as `loose` leaves out a shared checksum.
 *
 * @param entries corpus rows with ownerKind ("item", "object" or null) and ownerIds
 */
export function ownersLua(entries) {
  const owners = { item: new Map(), object: new Map() };
  for (const entry of entries) {
    const byId = owners[entry.ownerKind];
    if (!byId) continue;
    for (const id of entry.ownerIds ?? []) {
      byId.set(id, byId.has(id) && byId.get(id) !== entry.bookId ? null : entry.bookId);
    }
  }
  const lines = ["\towners = {"];
  for (const kind of ["item", "object"]) {
    lines.push(`\t\t${kind} = {`);
    for (const [id, bookId] of [...owners[kind].entries()].sort(([a], [b]) => compareIds(a, b))) {
      if (bookId !== null) lines.push(`\t\t\t[${id}] = ${luaId(bookId)},`);
    }
    lines.push("\t\t},");
  }
  lines.push("\t},");
  return lines;
}

/**
 * @param entries corpus rows: pageId, bookId, pageNumber, pageCount, title, text, and
 *   optionally ownerKind and ownerIds
 */
export function booksLua(entries) {
  // Sorted throughout, so re-exporting an unchanged corpus produces an identical file and a
  // diff shows only what actually moved.
  const sorted = canBeHad(entries).sort((a, b) => a.bookId - b.bookId || a.pageNumber - b.pageNumber);

  const books = new Map();
  for (const entry of sorted) {
    if (!books.has(entry.bookId)) books.set(entry.bookId, { title: entry.title, pages: [] });
    books.get(entry.bookId).pages.push(entry.pageId);
  }

  const lines = [HEADER, "SpokenReadablesData = {", "\tversion = 1,", "", ...indexLua(pageIndex(sorted))];

  lines.push("", "\tpages = {");
  for (const entry of [...sorted].sort((a, b) => a.pageId - b.pageId)) {
    lines.push(`\t\t[${entry.pageId}] = { book = ${entry.bookId}, number = ${entry.pageNumber}, text = ${quote(shownText(entry.text))} },`);
  }

  lines.push("\t},", "", "\tbooks = {");
  for (const bookId of [...books.keys()].sort((a, b) => a - b)) {
    const book = books.get(bookId);
    lines.push(`\t\t[${bookId}] = { title = ${quote(book.title)}, pages = { ${book.pages.join(", ")} } },`);
  }

  lines.push("\t},", "", ...ownersLua(sorted), "}", "");
  return lines.join("\n");
}
