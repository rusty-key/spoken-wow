// The sound pack's table: which clip narrates which page, and how long it runs.
//
// A module rather than a script, because two callers need it. `make readables-lookup` runs it
// by hand after a batch; the site runs it when the regeneration queue drains, so a take
// somebody generated in the explorer reaches the addon without anyone remembering to
// rebuild anything. lib/places/tools.ts imports its equivalent for exactly the same reason.
//
// Durations are recorded at generation time because the client cannot report the length of
// a sound file, and without them the player's Play button never resets itself.
//
// A language's pack also carries that language's page index. The English one, in the
// SpokenReadables addon, is keyed on the English title and a checksum of the English words, and a
// client in another locale shows neither: without its own index a translated page is never
// found at all. It ships in the pack because a client in that locale is the only one it can
// match, and a player there who wants the language installs the pack. A language no client
// runs in carries none.

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

import pg from "pg";

import { isClientLocale } from "../../../lib/locales.mjs";
import { packTimes } from "../../../lib/word-times.mjs";
import { canBeHad, compareIds, indexLua, luaId, pageIndex, quote } from "./lua.mjs";
import { normaliseText } from "./text.mjs";

const ROOT = new URL("../../../../", import.meta.url).pathname;
const LANG = "enUS";

/**
 * Where a language's table is written: English's beside its clips in the pack folder, which is
 * committed and zipped in place; another language's in its work area under build/, which
 * scripts/readables/package-audio.sh stages a pack from.
 */
export function lookupPath(lang) {
  return lang === LANG
    ? join(ROOT, "addons/SpokenReadablesAudio/Data/Sounds.lua")
    : join(ROOT, "build/readables", lang, "Data/Sounds.lua");
}

const HEADER = `-- AUTO-GENERATED by pipelines/readables/tools/lib/lookup.mjs. Do not edit by hand.
--
-- Durations are recorded at generation time because the client cannot report how long a
-- sound file is; without them the Play button never resets itself.
--
-- A page with no clip is simply absent. There is no stand-in: substituting unrelated audio
-- is worse than silence, because silence is honest about what is missing.
--
-- Globals rather than a private namespace: a data addon cannot reach into SpokenReadables's.
-- Regenerate with:  make readables-lookup`;

/**
 * The index entries for a language's pages: each page under every name its owners have in that
 * language, which is what ItemTextGetItem returns on that client, and under every text a
 * client may show.
 *
 * @param pages `{ pageId, numeric, bookId, pageNumber, ownerKind, ownerIds, inEnglish, texts,
 *   ownTitle }`, texts being the page as a client shows it, and ownTitle the title the
 *   language's own row carries
 * @param names `{ kind, entityId, name }` in that language, kind as entity_name spells it
 * @returns `{ known, extra }`: pages `Books.lua` has, and pages it lacks
 */
export function localeEntries(pages, names) {
  const byOwner = new Map(names.map((row) => [`${row.kind}:${row.entityId}`, row.name]));
  const known = [];
  const extra = [];
  for (const page of pages) {
    const kind = page.ownerKind === "object" ? "gameobject" : "item";
    const owned = page.ownerIds.map((id) => byOwner.get(`${kind}:${id}`)).filter(Boolean);
    const titles = [...new Set(owned.length ? owned : [page.ownTitle].filter(Boolean))].sort();
    const pageId = page.numeric ? Number(page.pageId) : page.pageId;
    const bookId = /^\d+$/.test(page.bookId) ? Number(page.bookId) : page.bookId;
    const entry = { pageId, bookId, pageNumber: page.pageNumber, texts: page.texts, titles };
    (page.inEnglish && page.numeric ? known : extra).push(entry);
  }
  return { known, extra };
}

/**
 * Data/Sounds.lua for a pack.
 *
 * @param lang the language the clips are recorded in
 * @param clips `{ pageId, file, durationSec, wordTimes }`, in page order
 * @param entries a language's localeEntries, or null for a language with no index
 */
export function packLua(lang, clips, entries = null) {
  const lines = [
    HEADER,
    "",
    "local ADDON_NAME = ...",
    "",
    "local pack = {",
    "\tversion = 1,",
    "\taddon = ADDON_NAME,",
    '\tquality = "high",',
    "\tbitrate = 128,",
    `\tlanguage = "${lang}",`,
    "\tpages = {",
  ];

  for (const row of clips) {
    // Null only for a take imported from a store this app did not cut. Written as 0 so
    // the addon can tell "unknown" from "short" and fall back to its own timer.
    const len = row.durationSec === null ? 0 : row.durationSec;
    // English's words for a page Books.lua has are Books.lua's, which the addon falls back to: a
    // copy here was 440 KB more in every English pack. A minted page is not in Books.lua.
    const inBooksLua = lang === LANG && typeof row.pageId === "number";
    const text = row.text == null || inBooksLua ? "" : `, text = ${quote(normaliseText(row.text))}`;
    // Absent for a take with no times: the captions then estimate.
    const times = row.wordTimes ? `, times = ${quote(packTimes(row.wordTimes))}` : "";
    lines.push(`\t\t[${luaId(row.pageId)}] = { file = ${quote(row.file)}, len = ${len}${text}${times} },`);
  }
  lines.push("\t},");

  if (entries) {
    // Every translated page, not only the voiced ones: a page found is also a page the
    // addon does not ask the player to contribute, and it falls back per page to another
    // language's clip like any other.
    if (entries.known.length > 0) lines.push("", ...indexLua(pageIndex(entries.known)));
    if (entries.extra.length > 0) {
      // Pages Spoken_Readables/Data/Books.lua lacks: found, placed and grouped from here. Older
      // versions of the addon read only `index` and `loose`, so they never meet an id they
      // cannot place.
      lines.push("", ...indexLua(pageIndex(entries.extra), "extra"), "", "\tplaces = {");
      for (const e of [...entries.extra].sort((a, b) => compareIds(a.pageId, b.pageId))) {
        lines.push(`\t\t[${luaId(e.pageId)}] = { book = ${luaId(e.bookId)}, number = ${e.pageNumber} },`);
      }
      lines.push("\t},", "", "\tbooks = {");
      const books = new Map();
      for (const e of [...entries.extra].sort((a, b) => a.pageNumber - b.pageNumber)) {
        if (!books.has(e.bookId)) books.set(e.bookId, []);
        books.get(e.bookId).push(e.pageId);
      }
      for (const bookId of [...books.keys()].sort(compareIds)) {
        lines.push(`\t\t[${luaId(bookId)}] = { pages = { ${books.get(bookId).map(luaId).join(", ")} } },`);
      }
      lines.push("\t},");
    }
  }

  lines.push(
    "}",
    "",
    "SpokenReadablesAudioPacks = SpokenReadablesAudioPacks or {}",
    "SpokenReadablesAudioPacks[ADDON_NAME] = pack",
    "",
  );
  return lines.join("\n");
}

/**
 * Writes Data/Sounds.lua from the current takes. Returns what it wrote.
 *
 * @param options.lang which language's takes, defaulting to English
 * @param options.out an explicit path, for tests
 */
export async function buildLookup({ lang = LANG, out = lookupPath(lang) } = {}) {
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("DATABASE_URL is not set -- the takes live in Postgres");

  const pool = new pg.Pool({ connectionString: url });
  try {
    // Joined to the corpus rather than trusting the take's lineId: a take for a page no
    // longer in the corpus has nothing to narrate, and an entry for it would be a row the
    // addon can never reach. One take per page, the newest, whatever else is flagged live. A
    // minted page is keyed by its id string, an extracted one by its page text id.
    const clips = await pool.query(
      `select * from (
       select distinct on (t."lineId")
              case when p."pageTextId" is not null then p."pageTextId"::text else substr(p."lineId", 3) end as "pageId",
              p."pageTextId" is not null as "numeric", p."pageTextId", p."lineId", p."bookId", b."title", b."text",
              t."file", t."durationSec", t."wordTimes"
         from "take" t
         join "book_line" b on b."lineId" = t."lineId" and b."lang" = t."lang" and b."isCurrent"
         join "book_page" p on p."lineId" = t."lineId" and p."aliasOf" is null
        where t."source" = 'readables' and t."isCurrent" and t."lang" = $1
        order by t."lineId", t."id" desc) c
        order by c."pageTextId" nulls last, c."lineId"`,
      [lang],
    );
    // A book nobody can have has no page the reader is shown, so no clip of it ships.
    const rows = canBeHad(
      clips.rows.map((r) => ({
        ...r,
        pageId: r.numeric ? Number(r.pageId) : r.pageId,
        bookId: /^\d+$/.test(r.bookId) ? Number(r.bookId) : r.bookId,
      })),
    );

    // A language no client runs in (Italian) has no index: no client shows its words, so a page
    // is always found by the client's own index and only played in this one.
    let entries = null;
    if (lang === LANG || isClientLocale(lang)) {
      // A page is indexed under its current text and under the words a client shows: the
      // newest version from the world database ('extracted') or, for a language it has none
      // of, from what a player's client sent in ('contributed') -- Portuguese books are all
      // the latter. A correction made here becomes the current text, not what is on screen,
      // so the current text alone would lose the page in game. Placed by book_page, which
      // fixes a page's book and number.
      const [pages, names] = await Promise.all([
        pool.query(
          `select case when p."pageTextId" is not null then p."pageTextId"::text else substr(p."lineId", 3) end as "pageId",
                  p."pageTextId" is not null as "numeric",
                  p."bookId", p."pageNumber", p."ownerKind", coalesce(p."ownerIds", '{}') as "ownerIds",
                  exists (select 1 from "book_line" e where e."lineId" = p."lineId" and e."lang" = $2 and e."isCurrent") as "inEnglish",
                  array_remove(array[
                    (select c."text" from "book_line" c where c."lineId" = p."lineId" and c."lang" = $1 and c."isCurrent"),
                    (select x."text" from "book_line" x where x."lineId" = p."lineId" and x."lang" = $1
                        and x."origin" in ('extracted', 'contributed')
                      order by (x."origin" = 'extracted') desc, x."version" desc limit 1)
                  ], null) as "texts",
                  (select c."title" from "book_line" c where c."lineId" = p."lineId" and c."lang" = $1 and c."isCurrent") as "ownTitle"
             from "book_page" p
            where p."aliasOf" is null
              and exists (select 1 from "book_line" c where c."lineId" = p."lineId" and c."lang" = $1)`,
          [lang, LANG],
        ),
        // The same rule for the owners' names.
        pool.query(
          `select distinct on ("kind", "entityId") "kind", "entityId", "name" from "entity_name"
            where "lang" = $1 and "origin" in ('extracted', 'contributed')
              and "kind" in ('gameobject', 'item')
            order by "kind", "entityId", ("origin" = 'extracted') desc, "version" desc`,
          [lang],
        ),
      ]);
      entries = localeEntries(pages.rows, names.rows);
      // English's own pages are indexed by Books.lua; only those it lacks are carried here.
      if (lang === LANG) entries = { known: [], extra: entries.extra };
    }

    await mkdir(dirname(out), { recursive: true });
    await writeFile(out, packLua(lang, rows, entries));

    return { clips: rows.length, pages: entries ? entries.known.length + entries.extra.length : null, path: out };
  } finally {
    await pool.end();
  }
}
