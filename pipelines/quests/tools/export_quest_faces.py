"""The appearance of every creature that gives or takes a quest or speaks one of its lines, for the
faces on the Quests tab.

    py -I pipelines/quests/tools/export_quest_faces.py     (the repack's MySQL running, as for `make compendium`)

The client answers "what does this creature look like" with a stand-in until it has cached the creature,
so the tab ships each one's model from `creature_template_model` and draws its face from that. Where the
repack has none, the model is the one Forever's server told players' clients (Efficient Games' creature
details, at export_compendium's pinned commit). A creature
with more than one model (one for each sex, or a random pick) is left out: which the player meets is the
client's to say, so its face waits for the client. So is a model the client's own tables lack
(CreatureDisplayInfo, and its CreatureModelData): the repack carries displays of later expansions, which
draw nothing. The client's tables are wago.tools' for the pinned build, or the CSVs in the folder
FOREVER_CLIENT_CSV names (file names in lower case, as a client export writes them).
Writes addons/Spoken_Quests/Data/QuestFaces.lua: SpokenQuestFaces[creatureID] = displayID.
"""
import csv
import gzip
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "pipelines" / "quests" / "tools"))
import export_compendium as ec  # noqa: E402

OUT = ROOT / "addons" / "Spoken_Quests" / "Data" / "QuestFaces.lua"
CLIENT_CSV = os.environ.get("FOREVER_CLIENT_CSV")


def client_table(name):
    if CLIENT_CSV:
        with open(Path(CLIENT_CSV) / f"{name.lower()}.csv", encoding="utf-8") as f:
            return list(csv.DictReader(f))
    return ec.table(name)


def drawable(display_rows, model_rows):
    """The display ids the client can draw: a CreatureDisplayInfo row whose model it has."""
    models = {int(row["ID"]) for row in model_rows}
    return {int(row["ID"]) for row in display_rows if int(row["ModelID"]) in models}


def faces(models, shown):
    """{creature: display} from {creature: its displays}: one display, which the client can draw."""
    return {creature: next(iter(displays)) for creature, displays in models.items()
            if len(displays) == 1 and next(iter(displays)) in shown}


def speakers(lines, dropped):
    """Every creature that says a quest's accept, progress or complete line. Not only the first of
    each: the packs' quest log names the last accept line's speaker as the giver."""
    return {int(line["npcId"]) for line in lines
            if line.get("source") in ec.SOURCES and line.get("questId") and line["questId"] not in dropped
            and line.get("npcType") == "creature" and line.get("npcId")}


def live_models(eg_sets):
    """{creature: its displays} as players' Forever clients were told them, from Efficient Games'
    creature details ({build: data}, oldest first): the latest build that saw the creature."""
    out = {}
    for data in eg_sets.values():
        for creature, record in data.get("creatures", {}).items():
            displays = {d["displayId"] for d in record.get("displays", []) if d.get("displayId")}
            if displays:
                out[int(creature)] = displays
    return out


def main():
    corpus = json.load(gzip.open(ec.CORPUS, "rt", encoding="utf-8"))
    ids = speakers(corpus["lines"], ec.left_out(corpus, ec.ignored_line_ids(ec.IGNORED)))
    cursor = ec.connect(ec.parse_args([])).cursor()
    for table in ("creature_queststarter", "creature_questender"):
        cursor.execute(f"SELECT DISTINCT id FROM {table}")
        ids.update(row[0] for row in cursor.fetchall())

    models = {}
    ids = sorted(ids)
    for start in range(0, len(ids), 500):
        chunk = ids[start:start + 500]
        marks = ",".join(["%s"] * len(chunk))
        cursor.execute(f"SELECT CreatureID, CreatureDisplayID FROM creature_template_model "
                       f"WHERE CreatureID IN ({marks}) AND CreatureDisplayID > 0 ORDER BY CreatureID, Idx", chunk)
        for creature, display in cursor.fetchall():
            models.setdefault(creature, set()).add(display)
    live = live_models(ec.eg_datasets("creature_details.enUS"))
    for creature in ids:
        if creature not in models and creature in live:
            models[creature] = live[creature]
    shown = drawable(client_table("CreatureDisplayInfo"), client_table("CreatureModelData"))
    chosen = faces(models, shown)

    lines = ["-- AUTO-GENERATED by pipelines/quests/tools/export_quest_faces.py. Do not edit by hand.",
             "--",
             "-- The model of every creature that gives, takes or speaks for a quest and has only one, which the",
             "-- client has:",
             "-- SpokenQuestFaces[creatureID] = displayID. The client answers with a stand-in for a creature it",
             "-- has not cached, so a face is drawn from this instead.",
             "",
             "SpokenQuestFaces = {"]
    row = []
    for creature in sorted(chosen):
        row.append(f"[{creature}]={chosen[creature]}")
        if len(row) == 12:
            lines.append("\t" + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("\t" + ", ".join(row) + ",")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf8", newline="\n")
    several = sum(1 for displays in models.values() if len(displays) > 1)
    print(len(ids), "creatures,", len(chosen), "with a face,", several, "with several models,",
          len(models) - several - len(chosen), "with a model the client lacks,", len(ids) - len(models),
          "with no model known ->", OUT)


if __name__ == "__main__":
    main()
