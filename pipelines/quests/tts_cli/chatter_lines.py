"""What NPCs say out loud in the world, for the addon's World Chatter part (Chatter.lua).

The corpus rows of source "chatter" (tts_cli/naming.py names them as follow-up lines are, by
broadcast_text id and voice) become addons/Spoken_Quests/ChatterLines.lua: by speaker, its name
and each line's broadcast id and text as the game says it. Chatter.lua matches arriving /say,
/yell and whisper chat against that text, and finds the recording in the packs' FollowupLookup
by the id.

Committed into the addon, not a pack: packaging the addon must never need a database. Read from
the corpus, Postgres's export, so rerun after export-corpus.
"""
import os

from tts_cli.naming import CHATTER
from tts_cli.quest_text import lua_string

DEFAULT_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "..", "..", "..", "addons", "Spoken_Quests", "ChatterLines.lua")

HEADER = """\
setfenv(1, VoiceOver)

-- Generated by `make quests-export-chatter-lines` from the corpus; do not edit by hand.
-- What NPCs say out loud in the world, by speaker: ChatterLines[creature id] = { name = "...",
-- { id = broadcast text id, text = "..." }, ... }. name is what a chat event calls the speaker on
-- a client that sends no GUID. See pipelines/quests/tts_cli/chatter_lines.py.
ChatterLines = {
"""



def _squash(text):
    return " ".join((text or "").split())


def chatter_lines(corpus):
    """{npc id: {"name": str, "lines": [(broadcast id, text)]}}, each id once per speaker.

    The game's own text (originalText), since that is what the chat event carries; a line's
    other voices (`~` ids) and player-gender forms are the same words, so the first one stands.
    """
    found = {}
    for line in corpus["lines"]:
        if line["source"] != CHATTER or line["npcType"] != "creature":
            continue
        broadcast = int(line["lineId"].split(":")[1])
        speaker = found.setdefault(line["npcId"], {"name": _squash(line["npcName"]), "lines": {}})
        speaker["lines"].setdefault(broadcast, _squash(line["originalText"]))
    return {npc: {"name": s["name"], "lines": sorted(s["lines"].items())} for npc, s in found.items()}


def render(lines):
    out = [HEADER]
    for npc in sorted(lines):
        name = lines[npc]["name"]
        out.append(f"    [{npc}] = {{ name = {lua_string(name)},\n" if name else f"    [{npc}] = {{\n")
        for broadcast, text in lines[npc]["lines"]:
            out.append(f"        {{ id = {broadcast}, text = {lua_string(text)} }},\n")
        out.append("    },\n")
    out.append("}\n")
    return "".join(out)


def export_chatter_lines(corpus, out_path=DEFAULT_OUT):
    """Write ChatterLines.lua; returns (lines, speakers)."""
    lines = chatter_lines(corpus)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(lines))
    return sum(len(s["lines"]) for s in lines.values()), len(lines)
