"""Writes the measured word times as the Lua data file the captions read.

    py -3 export.py --aligned aligned.jsonl --out WordTimes.lua

One string per recording: each word's start in hundredths of a second after the word before
(the first after the start), two base-64 digits a word. `matched` below --min-matched leaves a
recording out, so its captions keep the estimate. The file is data, not part of Spoken: it is
packaged and shipped apart from the addon, which reads the table it fills.
"""
import argparse
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from current import unchanged

DIGITS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
LARGEST = 64 * 64 - 1

# The addon source that plays each family, in the order the file lists them.
FAMILIES = ("quests", "gossip", "zones", "books")


def encode(times):
    """`times` (seconds, never decreasing) as a string, or None when a gap is too long to hold."""
    out, last = [], 0
    for time in times:
        at = round(time * 100)
        step = at - last
        if step < 0 or step > LARGEST:
            return None
        out.append(DIGITS[step // 64] + DIGITS[step % 64])
        last = at
    return "".join(out)


def decode(packed):
    times, at = [], 0
    for i in range(0, len(packed), 2):
        at += DIGITS.index(packed[i]) * 64 + DIGITS.index(packed[i + 1])
        times.append(at / 100)
    return times


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(rows, min_matched):
    kept = {family: {} for family in FAMILIES}
    skipped = {"unmatched": 0, "gap": 0}
    for row in rows:
        if row["matched"] < min_matched:
            skipped["unmatched"] += 1
            continue
        packed = encode(row["t"])
        if packed is None:
            skipped["gap"] += 1
            continue
        kept[row["family"]][row["id"]] = packed
    lines = [
        "-- AUTO-GENERATED by pipelines/timings/export.py. Do not edit by hand.",
        "--",
        "-- When each word of an English recording starts, found by listening to the voice packs'",
        "-- recordings (pipelines/timings/align.py). One string per recording, keyed by the source",
        "-- that plays it and the file it is played from: each word's start in hundredths of a second",
        "-- after the word before, two base-64 digits a word (Transcript.lua reads them). A recording",
        "-- with no entry has its words timed by estimate.",
        "--",
        "-- A global rather than a private namespace, as the other data files are: a data file cannot",
        "-- reach into the addon's environment.",
        "",
        "SpokenWordTimes = {",
    ]
    for family in FAMILIES:
        lines.append("\t%s = {" % family)
        for key in sorted(kept[family]):
            lines.append("\t\t[%s] = %s," % (lua_string(key), lua_string(kept[family][key])))
        lines.append("\t},")
    lines.append("}")
    return "\n".join(lines) + "\n", {f: len(v) for f, v in kept.items()}, skipped


def read_rows(path):
    """A results file's rows; a last line a worker is still writing is skipped."""
    rows = []
    for line in open(path, encoding="utf8"):
        try:
            rows.append(json.loads(line))
        except ValueError:
            pass
    return rows


def current_rows(rows, manifest):
    """The rows whose recording is still the length they were measured on, one per recording."""
    audio = {}
    for line in open(manifest, encoding="utf8"):
        row = json.loads(line)
        audio[(row["family"], row["id"])] = row["audio"]
    kept = {}
    for row in rows:
        key = (row["family"], row["id"])
        # Where a recording was heard more than once, the pass that matched the text best.
        if key in audio and unchanged(row, audio[key]) and row["matched"] >= kept.get(key, {"matched": -1})["matched"]:
            kept[key] = row
    print("rows:", len(rows), "current:", len(kept))
    return list(kept.values())


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--aligned", required=True, action="append",
                        help="align.py's --out (repeatable); its .N shards are read too")
    parser.add_argument("--manifest", help="drop rows whose recording has been cut again since (needs mutagen)")
    parser.add_argument("--out", required=True)
    parser.add_argument("--min-matched", type=float, default=0.85)
    args = parser.parse_args()
    rows = []
    for base in args.aligned:
        for path in [base] + sorted(glob.glob(base + ".*")):
            if os.path.exists(path):
                rows += read_rows(path)
    if args.manifest:
        rows = current_rows(rows, args.manifest)
    text, kept, skipped = render(rows, args.min_matched)
    with open(args.out, "w", encoding="utf8", newline="\n") as handle:
        handle.write(text)
    print("wrote", args.out, "%.1f MB" % (os.path.getsize(args.out) / 1e6), kept, "left out:", skipped)


if __name__ == "__main__":
    main()
