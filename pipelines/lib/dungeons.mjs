// The dungeons and raids, once for every pipeline and the addon (dungeons.json beside this file).
//
// The quests' and the books' exporters read dungeons.json to file a dungeon's quests and writings
// under the zone of its entrance. Run on its own, this writes addons/Spoken/Data/Dungeons.lua, the
// one table the Compendium's tabs read: each dungeon's zone, the Zones area that tells its story,
// and its name in every language, from Forever's client Map table (wago.mjs, cached).
//
//   node pipelines/lib/dungeons.mjs          (make dungeons)
//   node pipelines/lib/dungeons.mjs --check  fails where the file is not what this would write

import { readFileSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { FOREVER_BUILD, wagoTable } from "./wago.mjs";

const SOURCE = fileURLToPath(new URL("./dungeons.json", import.meta.url));
const OUT = fileURLToPath(new URL("../../addons/Spoken/Data/Dungeons.lua", import.meta.url));
export const LOCALES = ["deDE", "esES", "esMX", "frFR", "ptBR", "ruRU", "koKR", "zhCN", "zhTW", "itIT"];

const byMap = (table) => Object.fromEntries(Object.entries(table ?? {}).map(([map, row]) => [Number(map), row]));

/** dungeons.json, by map: { dungeons, worldBosses, instances, battlegrounds }, each { map: { name, zone, story? } }. */
export function loadDungeons(path = SOURCE) {
  const data = JSON.parse(readFileSync(path, "utf8"));
  return { dungeons: byMap(data.dungeons), worldBosses: byMap(data.worldBosses), instances: byMap(data.instances),
    battlegrounds: byMap(data.battlegrounds) };
}

/** Every instance map that is filed under a zone (dungeons, PvP halls, battlegrounds): { map: zone }. */
export function instanceZones(data = loadDungeons()) {
  const out = {};
  for (const part of [data.dungeons, data.instances, data.battlegrounds]) {
    for (const [map, row] of Object.entries(part)) out[map] = row.zone;
  }
  return out;
}

/** `text` as a Lua string literal. */
export function quote(text) {
  return `"${String(text).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/** The Lua file: `names` is { locale: { map: name } }, English under enUS. */
export function render(dungeons, names, worldBosses = {}) {
  const lines = Object.keys(dungeons).map(Number).sort((a, b) => a - b).map((map) => {
    const row = dungeons[map];
    const english = names.enUS?.[map] || row.name;
    const parts = [`zone = ${row.zone}`];
    if (row.story) parts.push(`story = { ${row.story[0]}, ${quote(row.story[1])} }`);
    parts.push(quote(english));
    for (const locale of LOCALES) {
      const name = names[locale]?.[map];
      if (name && name !== english) parts.push(`${locale} = ${quote(name)}`);
    }
    return `\t\t[${map}] = { ${parts.join(", ")} },`;
  });
  const worldLines = Object.keys(worldBosses).map(Number).sort((a, b) => a - b)
    .map((map) => {
      const parts = [`zone = ${worldBosses[map].zone}`];
      const zones = worldBosses[map].bossZones;
      if (zones) parts.push(`bossZones = { ${Object.keys(zones).sort().map((key) => `[${quote(key)}] = ${zones[key]}`).join(", ")} }`);
      return `\t\t[${map}] = { ${parts.join(", ")} },`;
    });
  return `-- AUTO-GENERATED by pipelines/lib/dungeons.mjs from pipelines/lib/dungeons.json. Do not edit by hand.
--
-- The dungeons and raids, by instance map, for every tab of Azeroth's Compendium: \`zone\`, the
-- uiMapID of the zone their entrance is in, where the tabs list them; \`story\`, the Zones area
-- that tells their story ({ uiMapID, key }), absent where none does; and their name in every
-- language, from the client's Map table (Forever ${FOREVER_BUILD}, wago.tools). The quests' and the
-- books' exporters file a dungeon's quests and writings by the same maps. Regenerate with:
--   make dungeons
--
-- A global rather than a private namespace: a data file cannot reach into the addon's environment.

SpokenDungeons = {
\tversion = 1,

\tdungeons = {
${lines.join("\n")}
\t},

\t-- The maps of the world bosses, by instance map: \`zone\` the uiMapID of the zone they stand in. The
\t-- Bosses tab lists their bosses under the zone, with no card for the map; \`bossZones\`, where a map's
\t-- bosses stand in different zones, the zone of each boss by its key.
\tworldBosses = {
${worldLines.join("\n")}
\t},
}
`;
}

async function main() {
  const { dungeons, worldBosses } = loadDungeons();
  const names = {};
  for (const locale of ["enUS", ...LOCALES]) {
    names[locale] = {};
    for (const row of await wagoTable("Map", { build: FOREVER_BUILD, locale })) {
      const map = Number(row.ID);
      if ((dungeons[map] || worldBosses[map]) && row.MapName_lang) names[locale][map] = row.MapName_lang;
    }
  }
  const text = render(dungeons, names, worldBosses);
  if (process.argv.includes("--check")) {
    const current = (await readFile(OUT, "utf8")).replace(/\r\n/g, "\n");
    if (current !== text) {
      console.error(`${OUT} is not what pipelines/lib/dungeons.json gives: run make dungeons`);
      process.exit(1);
    }
    console.log(`${OUT} is up to date`);
    return;
  }
  await writeFile(OUT, text);
  console.log(`wrote ${Object.keys(dungeons).length} dungeons to ${OUT}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
