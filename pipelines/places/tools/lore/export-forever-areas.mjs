#!/usr/bin/env node
// Writes addons/Spoken_Places/Data/ForeverAreas.lua: the areas only the Forever client has.
//
//   node tools/lore/export-forever-areas.mjs
//
// The corpus ships for both clients, so Subzones.lua holds the areas Forever added to the old
// zones (Camp Gev'rek in Mulgore, Blackmaw Hold in Azshara) as well as Era's. An Era client can
// never report those, so Lore of Azeroth leaves them out there: listed, they would stay
// undiscovered for good and keep their zone short of everything found. An area is Forever's
// alone when its name is in Forever's AreaTable (seed/camelot-areas.json) and not in Era's
// (seed/era-areas.json). Run it again after the subzones or either seed change.
//
// It also writes what seed/forever-places.json says by hand: Forever's spelling of a place the
// lore keeps under another key (ForeverNames: Legashi Encampment is the frozen legash
// encampment), and the places listed that no Forever player can reach (NotOnForever), with the
// lore's entry under a renamed spelling, which is the same place twice.

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { loadEraAreas } from "../lib/era.mjs";
import { readJson, ROOT } from "../lib/wiki.mjs";

const SUBZONES = join(ROOT, "addons/Spoken_Places/Data/enUS/Subzones.lua");
const PLACES = join(ROOT, "pipelines/places/tools/seed/forever-places.json");
const OUT = join(ROOT, "addons/Spoken_Places/Data/ForeverAreas.lua");

function table(name, byZone) {
  const lines = [`SpokenPlaces.${name} = {`];
  for (const mapID of [...byZone.keys()].sort((a, b) => a - b)) {
    lines.push(`\t[${mapID}] = {`);
    for (const key of [...byZone.get(mapID)].sort()) lines.push(`\t\t[${JSON.stringify(key)}] = true,`);
    lines.push("\t},");
  }
  lines.push("}");
  return lines;
}

async function main() {
  const era = await loadEraAreas();
  const places = await readJson(PLACES);
  const text = await readFile(SUBZONES, "utf8");
  const byZone = new Map();
  const notOnForever = new Map(
    Object.entries(places.notOnForever).map(([mapID, keys]) => [Number(mapID), new Set(Object.keys(keys))]),
  );
  let zone = null;
  for (const line of text.split(/\r?\n/)) {
    const z = line.match(/^\t\[(\d+)\] = \{/);
    if (z) {
      zone = Number(z[1]);
      continue;
    }
    const k = line.match(/^\t\t\["(.+)"\] = \{$/);
    if (k && zone !== null && !era.keys.has(k[1])) {
      if (!byZone.has(zone)) byZone.set(zone, []);
      byZone.get(zone).push(k[1]);
    }
    // Listed from the frozen key too, so the Forever spelling stays hidden after its own
    // discovered row is gone: a later discovery would otherwise list the place twice.
    for (const [name, { key }] of Object.entries(places.renamed)) {
      if (k && zone !== null && (k[1] === name || k[1] === key)) {
        if (!notOnForever.has(zone)) notOnForever.set(zone, new Set());
        notOnForever.get(zone).add(name);
      }
    }
  }
  const lines = [
    "-- AUTO-GENERATED by tools/lore/export-forever-areas.mjs. Do not edit by hand.",
    "--",
    "-- The areas only the Forever client has: in its AreaTable and not in Era's (build " + era.build + ").",
    "-- Lore of Azeroth leaves them out on any other client, which can never report them. Keyed as",
    "-- Subzones.lua is: uiMapID, then the normalised area name.",
    "",
    "local _, SpokenPlaces = ...",
    "",
    ...table("ForeverOnlyAreas", byZone),
    "",
    "-- Forever's spelling of a place the lore keeps under another key, normalised: the key the",
    "-- place's lines, clip and picture are frozen under (pipelines/places/tools/seed/forever-places.json).",
    "SpokenPlaces.ForeverNames = {",
    ...Object.entries(places.renamed)
      .sort(([a], [b]) => (a < b ? -1 : 1))
      .map(([name, { key }]) => `\t[${JSON.stringify(name)}] = ${JSON.stringify(key)},`),
    "}",
    "",
    "-- The places the lore lists that no Forever player can reach, and a renamed place's entry under",
    "-- Forever's spelling: Lore of Azeroth leaves them out on Forever.",
    ...table("NotOnForever", notOnForever),
    "",
  ];
  const count = [...byZone.values()].reduce((n, keys) => n + keys.length, 0);
  await writeFile(OUT, lines.join("\n"));
  console.log(`wrote ${count} Forever-only areas in ${byZone.size} zones to ${OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
