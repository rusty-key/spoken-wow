"""Data/Cameras.lua: the lens every boss's 3D model is drawn with, and which bosses share a model file.

The game frames each boss itself, from the bounding box of its loaded model (TextView.lua), so there is no
camera to work out here. What the game needs from the pipeline is the lens and pose it frames with, and the
model file behind each display id, so that bosses drawn from one file share a hand nudge. That file comes from
the client's tables in ~/Documents/forever-db/csv (creaturedisplayinfo.csv, creaturemodeldata.csv), for every
display id in Data/Creatures.lua.

    python model_cameras.py     write addons/Spoken_Bosses/Data/Cameras.lua (make bosses-cameras)

Cameras.lua is written whole, for every display id, or not at all.
"""
import csv
import functools
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", "..", ".."))
CSV = os.path.expanduser("~/Documents/forever-db/csv")
CREATURES = os.path.join(ROOT, "addons/Spoken_Bosses/Data/Creatures.lua")
OUT = os.path.join(ROOT, "addons/Spoken_Bosses/Data/Cameras.lua")
# The field of view the client draws with, the full vertical angle: it matches the size of the figure in
# screenshots of the client's own camera (within a few percent for three of five bosses). TextView frames a
# boss with it and turns a hand nudge (frame heights) into the scene's units with it, so it is written into
# Cameras.lua rather than kept in two places.
FOV_DEGREES = 27.78
# The animation the game plays (TextView's SetSequence), written into Cameras.lua as the view's sequence.
SHOWN = 0


@functools.lru_cache(maxsize=None)
def table(name):
    with open(os.path.join(CSV, name), newline="", encoding="utf8") as f:
        return {int(r["ID"]): r for r in csv.DictReader(f)}


def displays():
    text = open(CREATURES, encoding="utf8").read()
    return sorted({int(m) for m in re.findall(r"display = (\d+)", text)})


def model_file(display):
    """The FileDataID of the model a display id is drawn from, or None."""
    row = table("creaturedisplayinfo.csv").get(display)
    md = table("creaturemodeldata.csv").get(int(row["ModelID"])) if row else None
    return int(md["FileDataID"]) if md else None


def write(groups, path=None):
    """The one writer of Cameras.lua. `groups` is { display id: model file } for every display id in
    Creatures.lua. A display id without a model file is as missing as one left out: TextView keys a hand nudge
    by the model file, and a boss with none would never match its nudge."""
    missing = [d for d in displays() if not groups.get(d)]
    if missing:
        sys.exit(f"{len(missing)} display ids have no model file, nothing written: {missing[:12]}")
    lines = ["-- AUTO-GENERATED by pipelines/places/tools/bosses/model_cameras.py (make bosses-cameras) from the client's creature tables.",
             "-- Do not edit by hand: a boss moved by hand in the game goes to Data/CameraNudges.lua (docs/places/BOSSES.md).",
             "-- SpokenBossCameraView is the lens (full vertical field of view, in degrees) and the animation sequence",
             "-- every boss is drawn with. TextView reads both, and frames each boss itself from its loaded model.",
             "SpokenBossCameraView = { fov = %s, sequence = %d }" % (FOV_DEGREES, SHOWN),
             "-- SpokenBossCameraGroups[display id] = the model file it is drawn from. Bosses on one file share a hand nudge.",
             "SpokenBossCameraGroups = {"]
    for display in sorted(groups):
        lines.append("\t[%d] = %d," % (display, groups[display]))
    lines.append("}")
    path = path or OUT
    with open(path, "w", encoding="utf8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(len(groups), "display ids written to", path)


if __name__ == "__main__":
    write({d: model_file(d) for d in displays()})
