"""Tests for model_cameras.py. Run: py -m unittest discover -s pipelines/places/tools/bosses -p "test_*.py"
(python3 on Linux and macOS)."""
import contextlib
import io
import os
import sys
import tempfile
import unittest
from unittest import mock

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import model_cameras as mc  # noqa: E402


def read(path):
    with open(path, encoding="utf8") as f:
        return f.read()


class WriteTest(unittest.TestCase):
    def write(self, groups):
        """(the file's text or None, whether the writer refused) for a writer run over displays 10, 20 and 30."""
        with tempfile.TemporaryDirectory() as folder, mock.patch.object(mc, "displays", lambda: [10, 20, 30]):
            path = os.path.join(folder, "Cameras.lua")
            refused = False
            try:
                with contextlib.redirect_stdout(io.StringIO()):
                    mc.write(groups, path)
            except SystemExit:
                refused = True
            return (read(path) if os.path.exists(path) else None), refused

    def test_writes_the_generated_header_the_view_and_the_groups_only(self):
        text, refused = self.write({10: 111, 20: 111, 30: 222})
        self.assertFalse(refused)
        self.assertTrue(text.startswith("-- AUTO-GENERATED by pipelines/places/tools/bosses/model_cameras.py"))
        self.assertIn("SpokenBossCameraView = { fov = 27.78, sequence = 0 }", text)
        self.assertIn("\t[10] = 111,\n\t[20] = 111,\n\t[30] = 222,\n", text)
        self.assertNotIn("SpokenBossCameras =", text)

    def test_refuses_a_partial_set_of_displays_and_writes_nothing(self):
        self.assertEqual(self.write({10: 111, 20: 111}), (None, True))

    def test_a_display_without_a_model_file_is_as_missing_as_one_left_out(self):
        self.assertEqual(self.write({10: 111, 20: None, 30: 222}), (None, True))


if __name__ == "__main__":
    unittest.main()
