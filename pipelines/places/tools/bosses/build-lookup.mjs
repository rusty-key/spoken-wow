#!/usr/bin/env node
//
// The live boss takes -> SpokenBossesAudio/Data/Sounds.lua.
//
//   node pipelines/places/tools/bosses/build-lookup.mjs [--lang deDE]
//
// English writes the pack in the tree; another language writes build/bosses/<lang>/. Each
// entry's file is the take's own: the site assigned it from the catalogue order, and the
// lookup must never disagree with it, so nothing here recomputes a path.

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { packTimes } from "../../../lib/word-times.mjs";
import { loadEnvFile } from "../lib/env.mjs";
import { close, readBosses, readLiveTakes, requireDatabase } from "./store.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../../..");
const BASE_LANG = "enUS";

function luaString(text) {
  return `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

// Takes store a POSIX path; WoW addresses files with backslashes.
function fields(entry) {
  const times = entry.times ? `, times = ${luaString(packTimes(entry.times))}` : "";
  return `file = ${luaString(entry.file.replace(/\//g, "\\"))}, len = ${entry.len}${times}`;
}

/** The take rows of live bosses as lookup entries; takes naming no live boss come back in `skipped`. */
export function buildEntries(takes, bosses) {
  const live = new Set(bosses.filter((b) => !b.retired).map((b) => `boss:${b.map}:${b.key}`));
  const entries = [];
  const skipped = [];
  for (const take of takes) {
    if (!live.has(take.lineId)) {
      skipped.push(take.file);
      continue;
    }
    const [, map, ...rest] = take.lineId.split(":");
    entries.push({
      map: Number(map),
      key: rest.join(":"),
      file: take.file,
      len: take.durationSec,
      ...(take.wordTimes ? { times: take.wordTimes } : {}),
    });
  }
  return { entries, skipped };
}

/** @param entries {{ map: number, key: string, file: string, len: number, times?: number[] }[]} */
export function renderLookup(entries) {
  const byMap = new Map();
  for (const e of entries) {
    if (!byMap.has(e.map)) byMap.set(e.map, []);
    byMap.get(e.map).push(e);
  }

  const lines = [
    "-- AUTO-GENERATED by pipelines/places/tools/bosses/build-lookup.mjs. Do not edit by hand.",
    "--",
    "-- Durations are recorded at generation time because the client cannot report",
    "-- how long a sound file is; without them the Play button never resets itself.",
    "",
    "local ADDON_NAME = ...",
    "",
    "local pack = {",
    // Bumped only when the shape below changes in a way Spoken_Bosses cannot read.
    "\tversion = 1,",
    "\tbosses = {",
  ];

  for (const map of [...byMap.keys()].sort((a, b) => a - b)) {
    lines.push(`\t\t[${map}] = {`);
    const rows = byMap.get(map).sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
    for (const e of rows) lines.push(`\t\t\t[${luaString(e.key)}] = { ${fields(e)} },`);
    lines.push("\t\t},");
  }

  lines.push(
    "\t},",
    "}",
    "",
    "-- C_AddOns is the modern home of GetAddOnMetadata and the global is the older",
    "-- one; a pack that reads only through C_AddOns errors at load on older clients.",
    "local GetAddOnMeta = (C_AddOns and C_AddOns.GetAddOnMetadata) or GetAddOnMetadata",
    "",
    "-- The folder name comes from the loader, so one generated file serves every pack",
    "-- built from this tree: they differ only in their .toc and their mp3s.",
    "pack.addon = ADDON_NAME",
    'pack.quality = GetAddOnMeta(ADDON_NAME, "X-SpokenBosses-Quality") or "standard"',
    'pack.bitrate = tonumber(GetAddOnMeta(ADDON_NAME, "X-SpokenBosses-Bitrate")) or 0',
    'pack.packVersion = GetAddOnMeta(ADDON_NAME, "Version") or "dev"',
    'pack.language = GetAddOnMeta(ADDON_NAME, "X-SpokenBosses-Language") or "enUS"',
    "",
    "-- Keyed by folder name so two packs installed at once both register instead of",
    "-- the second silently overwriting the first.",
    "SpokenBossesAudioPacks = SpokenBossesAudioPacks or {}",
    "SpokenBossesAudioPacks[ADDON_NAME] = pack",
    "",
  );
  return lines.join("\n");
}

export function lookupPath(lang) {
  return lang === BASE_LANG
    ? join(ROOT, "addons/SpokenBossesAudio/Data/Sounds.lua")
    : join(ROOT, "build/bosses", lang, "Data/Sounds.lua");
}

export async function buildLookup(lang = BASE_LANG) {
  requireDatabase("bosses-lookup");
  const [takes, bosses] = await Promise.all([readLiveTakes(lang), readBosses({ includeRetired: true })]);
  const { entries, skipped } = buildEntries(takes, bosses);
  const path = lookupPath(lang);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, renderLookup(entries));
  return { count: entries.length, skipped, path };
}

async function main() {
  const at = process.argv.indexOf("--lang");
  const lang = at > 0 ? process.argv[at + 1] : BASE_LANG;
  const result = await buildLookup(lang);
  console.log(`wrote ${result.path}`);
  console.log(`  ${result.count} bosses`);
  if (result.skipped.length > 0) {
    console.log(`  ${result.skipped.length} live takes left out, no live boss: ${result.skipped.join(", ")}`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  loadEnvFile()
    .then(main)
    .catch((err) => {
      console.error(`error: ${err.message}`);
      process.exitCode = 1;
    })
    .finally(() => close());
}
