// The alias tables of Data/<locale>/Aliases.lua, from the client's AreaTable rows. Kept apart
// from tools/locale/build-aliases.mjs, which fetches the tables, so they can be tested on rows.

import { luaString } from "./wiki.mjs";

/**
 * {aliases: localized name -> corpus key, ambiguous: names left out} from one build's English
 * and localized AreaTable. A localized name that stands for two different keys cannot be
 * resolved from the name alone, so neither reading is stored: a wrong alias shows the wrong
 * lore, which is worse than the miss it replaces.
 */
export function aliasesOf(englishRows, localizedRows, wanted, keyOf) {
  const englishById = new Map(englishRows.map((row) => [row.ID, (row.AreaName_lang || "").trim()]));
  const aliases = new Map();
  const ambiguous = new Set();
  for (const row of localizedRows) {
    const localized = (row.AreaName_lang || "").trim();
    const englishName = englishById.get(row.ID);
    if (!localized || !englishName) continue;

    const key = keyOf(englishName);
    if (localized === englishName) continue;
    if (!wanted.has(key)) continue;

    const existing = aliases.get(localized);
    if (existing && existing !== key) {
      ambiguous.add(localized);
      aliases.delete(localized);
    } else if (!ambiguous.has(localized)) {
      aliases.set(localized, key);
    }
  }
  return { aliases, ambiguous };
}

/**
 * localized name -> (uiMapID -> corpus key), for the names a client gives more than one place.
 *
 * The flat table drops such a name, or keeps the reading of the build read first, so the other
 * place gets no story, or the wrong one. The zone the player is in tells them apart where the
 * places' stories are kept under different zones: esES names Thunder Bluff's Spirit Rise and
 * Forever's Rise of Spirits both "Alto de los Espíritus". Every build's rows count, a name the
 * same as English included, so a name one build gives one place and another build another is
 * shared too. A zone two of the places share is left out: the name cannot tell them apart there.
 *
 * @param builds [{ english, localized, keyOf }]: each build's AreaTable rows, English and localized
 * @param mapsOf corpus key -> the uiMapIDs its stories are kept under
 */
export function zoneAliasesOf(builds, mapsOf) {
  const keysOf = new Map();
  for (const { english, localized, keyOf } of builds) {
    const englishById = new Map(english.map((row) => [row.ID, (row.AreaName_lang || "").trim()]));
    for (const row of localized) {
      const name = (row.AreaName_lang || "").trim();
      const englishName = englishById.get(row.ID);
      if (!name || !englishName) continue;
      const key = keyOf(englishName);
      if (!mapsOf.has(key)) continue;
      if (!keysOf.has(name)) keysOf.set(name, new Set());
      keysOf.get(name).add(key);
    }
  }

  const byZone = new Map();
  for (const [name, keys] of keysOf) {
    if (keys.size < 2) continue;
    const owners = new Map();
    for (const key of keys) {
      for (const mapID of mapsOf.get(key)) {
        if (!owners.has(mapID)) owners.set(mapID, new Set());
        owners.get(mapID).add(key);
      }
    }
    const zones = new Map();
    for (const [mapID, owner] of owners) if (owner.size === 1) zones.set(mapID, [...owner][0]);
    if (zones.size) byZone.set(name, zones);
  }
  return byZone;
}

export function emitAliases(locale, aliases, builds, byZone = new Map()) {
  const lines = [
    "-- AUTO-GENERATED by tools/locale/build-aliases.mjs. Do not edit by hand.",
    "--",
    `-- Area names as a ${locale} client reports them, mapped to the English keys the`,
    "-- corpus is stored under. Built by joining AreaTable's localized and English",
    `-- strings on their shared ID, from client builds ${builds.join(" (Forever), then ")} (Era).`,
    "--",
    "-- Keyed by the raw client name: SpokenZones:NormaliseAreaKey reduces a name to",
    "-- [a-z0-9 ], which erases a Cyrillic or Chinese name entirely.",
    "",
    "local _, SpokenZones = ...",
    "",
    `if not SpokenZones:ShouldLoadAliases("${locale}") then`,
    "\treturn",
    "end",
    "",
    "local aliases = {",
  ];

  for (const name of [...aliases.keys()].sort()) {
    lines.push(`\t[${luaString(name)}] = ${luaString(aliases.get(name))},`);
  }
  lines.push("}", "");

  if (byZone.size === 0) {
    lines.push(`SpokenZones:RegisterAliases("${locale}", aliases)`, "");
    return lines.join("\n");
  }

  lines.push(
    "-- Names the client gives more than one place, by the uiMapID each place's story is kept",
    "-- under. Read before the table above (SpokenZones:ResolveAreaKey).",
    "local byZone = {",
  );
  for (const name of [...byZone.keys()].sort()) {
    const zones = [...byZone.get(name)].sort(([a], [b]) => a - b);
    const cells = zones.map(([mapID, key]) => `[${mapID}] = ${luaString(key)}`).join(", ");
    lines.push(`\t[${luaString(name)}] = { ${cells} },`);
  }
  lines.push("}", "", `SpokenZones:RegisterAliases("${locale}", aliases, byZone)`, "");
  return lines.join("\n");
}
