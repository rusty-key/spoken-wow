#!/usr/bin/env node
// Fetches each boss's lore from warcraft.wiki.gg (CC BY-SA 4.0) and writes Data/Stories.lua for
// Spoken NPCs: SpokenBossStories[map][key] = "the lead of its article", era-filtered to Classic
// as the zones' lore is, with the lore sections of the article where the lead is thin.
//
// The bosses come from addons/Spoken_NPCs/Data/Bosses.lua. Pages are cached in cache/ beside the
// zones' (lib/wiki.mjs: identified agent, one request every half second).
//
// Usage: node tools/scrape-bosses.mjs [--out <file>] [--refresh] [--only <boss name>]
//   --out      where to write (default: addons/Spoken_NPCs/Data/Stories.lua)
//   --refresh  ask the wiki again for pages already cached
//
// The result is the wiki's text, not the project's data: it is kept out of commits to the
// repository, and its credit is in THIRD_PARTY.md.

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { ROOT, fetchLoreText, luaString, sourceUrl } from "./lib/wiki.mjs";

const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const value = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : null);
const OUT = value("--out") ?? join(ROOT, "addons/Spoken_NPCs/Data/Stories.lua");
const MAX_CHARS = 1800;

/** [{ map, key, name }] from Data/Bosses.lua. */
async function readBosses() {
  const text = await readFile(join(ROOT, "addons/Spoken_NPCs/Data/Bosses.lua"), "utf8");
  const out = [];
  let map = null;
  for (const line of text.split(/\r?\n/)) {
    const head = line.match(/^\t\t\[(\d+)\] = \{/);
    if (head) {
      map = Number(head[1]);
      continue;
    }
    const boss = line.match(/\{ id = \d+, ids = \{[^}]*\}, key = "([^"]+)", "((?:[^"\\]|\\.)*)"/);
    if (boss && map !== null) out.push({ map, key: boss[1], name: boss[2].replace(/\\(.)/g, "$1") });
  }
  return out;
}

/** The wiki title to ask for: the boss's name; "Name (boss)" where the plain page is not about it. */
const TITLES = (name) => [name, `${name} (boss)`, `${name} (NPC)`];

function trim(text) {
  if (text.length <= MAX_CHARS) return text;
  const paragraphs = text.split("\n\n");
  let out = "";
  for (const paragraph of paragraphs) {
    if (out && out.length + paragraph.length + 2 > MAX_CHARS) break;
    out = out ? out + "\n\n" + paragraph : paragraph;
  }
  return out;
}

async function storyFor(name, refresh) {
  for (const title of TITLES(name)) {
    const res = await fetchLoreText(title, { refresh, minChars: 400 });
    if (res.missing || res.cleaned.empty || res.cleaned.full.length < 40) continue;
    // A disambiguation page is a list of other pages: not a story.
    if (/may refer to|can refer to|disambiguation/i.test(res.cleaned.full.slice(0, 200))) continue;
    return { text: trim(res.cleaned.full), title: res.resolvedTitle };
  }
  return null;
}

async function main() {
  const only = value("--only");
  const bosses = (await readBosses()).filter((boss) => !only || boss.name === only);
  const stories = {};
  const sources = [];
  const missing = [];
  let n = 0;
  for (const boss of bosses) {
    n++;
    const found = await storyFor(boss.name, flag("--refresh"));
    if (!found) {
      missing.push(`${boss.map}/${boss.name}`);
      console.log(`[${n}/${bosses.length}] ${boss.name}: no page`);
      continue;
    }
    stories[boss.map] ??= {};
    stories[boss.map][boss.key] = found.text;
    sources.push({ ...boss, title: found.title });
    console.log(`[${n}/${bosses.length}] ${boss.name}: ${found.text.length} chars (${found.title})`);
  }

  const blocks = Object.keys(stories)
    .map(Number)
    .sort((a, b) => a - b)
    .map((map) => {
      const lines = Object.keys(stories[map])
        .sort()
        .map((key) => `\t\t[${luaString(key)}] = ${luaString(stories[map][key])},`);
      return `\t[${map}] = {\n${lines.join("\n")}\n\t},`;
    });
  const lua = `-- GENERATED by pipelines/zones/tools/scrape-bosses.mjs from warcraft.wiki.gg, CC BY-SA 4.0
-- (https://warcraft.wiki.gg/, each article's page history lists its authors). Not for commits to
-- the repository: a boss's story is the site's data.
--
-- SpokenBossStories[instance map][boss key] = the boss's story.

SpokenBossStories = SpokenBossStories or {}
for map, stories in pairs({
${blocks.join("\n")}
}) do
\tSpokenBossStories[map] = stories
end
`;
  await writeFile(OUT, lua);
  await writeFile(OUT.replace(/\.lua$/, ".sources.txt"), sources.map((s) => `${s.map}\t${s.key}\t${sourceUrl(s.title)}`).join("\n") + "\n");
  console.log(`wrote ${sources.length} stories to ${OUT}; ${missing.length} bosses have no page:\n${missing.join("\n")}`);
}

await main();
